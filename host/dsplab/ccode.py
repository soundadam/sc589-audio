"""Write coefficient tables as a C source and header pair.

The firmware builds on the Windows host from the committed files, so the
generated pair is committed next to the code that uses it; the generator named
in the file header is the one place to change it.
"""

from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

@dataclass
class Table:
    """One `const float` array.

    name        C identifier of the array
    dim         array dimension as written in C, e.g. "LOWPASS_IIR_SECTIONS * BIQUAD_COEFFS"
    values      the entries, flattened in C order
    comment     what the array holds, placed above its declaration
    defines     (macro, value) pairs the header defines before the declaration
    per_line    entries per source line, e.g. one second-order section
    """

    name: str
    dim: str
    values: np.ndarray
    comment: str
    defines: list[tuple[str, int]] = field(default_factory=list)
    per_line: int = 4


def _array_body(values, per_line):
    # 9 significant digits round-trip any float32
    cells = ["%.8ef" % v for v in np.asarray(values, dtype=np.float32).ravel()]
    width = max(map(len, cells))
    rows = [", ".join(c.rjust(width) for c in cells[i:i + per_line])
            for i in range(0, len(cells), per_line)]
    return ",\n".join("\t" + r for r in rows)


def _comment(text, indent=""):
    lines = text.strip().splitlines()
    return "\n".join([indent + "/*"] + [(indent + " * " + l).rstrip() for l in lines] + [indent + " */"])


def write(stem, tables, *, brief, details, generator, includes=()):
    """Write <stem>.h and <stem>.c holding `tables`.

    brief       one line for the @brief tag
    details     paragraph under it: the design the numbers come from
    generator   command that regenerates the pair, quoted in both files
    includes    headers the declarations need (e.g. "dsp/biquad.h")
    """
    stem = Path(stem)
    guard = "__%s_H__" % stem.name.upper()
    notice = "Generated by `%s`;\nedit the design there, not this file." % generator

    head = [
        "/*!",
        " * @file      %s.h" % stem.name,
        " * @brief     %s" % brief,
        " *",
    ]
    head += [(" *            " + l).rstrip() for l in (details.strip() + "\n\n" + notice).splitlines()]
    head += [" */", "", "#ifndef %s" % guard, "#define %s" % guard, ""]
    for inc in includes:
        head.append('#include "%s"' % inc)
    if includes:
        head.append("")
    for t in tables:
        head.append(_comment(t.comment))
        for macro, value in t.defines:
            head.append("#define %s (%du)" % (macro, value))
        head.append("extern const float %s[%s];" % (t.name, t.dim))
        head.append("")
    head.append("#endif /* %s */" % guard)

    src = [
        "/*!",
        " * @file      %s.c" % stem.name,
        " * @brief     %s" % brief,
        " *",
    ]
    src += [" *            " + l for l in notice.splitlines()]
    src += [
        " */",
        "",
        '#include "dsp/%s.h"' % stem.name,
    ]
    for t in tables:
        src += ["", "const float %s[%s] =" % (t.name, t.dim), "{", _array_body(t.values, t.per_line), "};"]

    stem.with_suffix(".h").write_text("\n".join(head) + "\n")
    stem.with_suffix(".c").write_text("\n".join(src) + "\n")

