"""E01 figures and numbers for the report, from the design and the board log.

    make board                                   # writes build/board.log
    uv run coursework/E01-fir-iir/figures.py     # writes build/E01/

The impulse figure overlays what the SHARC computed from the same
coefficients (FilterReport) on the design; that checks the float
implementation, not the analog path. results.tex holds the numbers the report
quotes as LaTeX macros, so the text never repeats a value by hand.
"""

import argparse
from pathlib import Path

import numpy as np

import design
from dsplab import boardlog, plot, response

REPO = design.REPO
OUT = REPO / "build" / "E01"
BOARD_LOG = REPO / "build" / "board.log"

# Phase and group delay are shown over the pass band and transition only:
# the FIR's first zero (about 4.7 kHz) flips its phase by 180 degrees there
DETAIL_HZ = 4000.0
# Samples of the IIR impulse response shown; the rest is below 1e-3 of the peak
IIR_SHOWN = 160
# Points of the gain table in the report
TABLE_HZ = (500.0, 1000.0, 1500.0, 2000.0, 2500.0, 3000.0, 4000.0, 6000.0, 12000.0)

FIR_STYLE = {"color": "C0"}
IIR_STYLE = {"color": "C3"}


def _macro(name, value):
    return "\\newcommand{\\%s}{%s}\n" % (name, value)


def _db(value):
    """Gain in dB for the text: a true minus sign, and no -0.00."""
    return "\\num{%.2f}" % (round(value, 2) + 0.0)


def results_tex(fs, h, sos, run, fir_design, iir_design):
    """LaTeX macros for every number the report quotes."""
    fir_ir_err = np.abs(run.impulse["fir"][:len(h)] - h).max()
    iir_ref = response.sos_impulse(sos, len(run.impulse["iir"]))
    iir_ir_err = np.abs(run.impulse["iir"] - iir_ref).max()

    passband = fir_design.f <= design.CUTOFF_HZ
    iir_gd = iir_design.gd[passband]
    peak = np.nanargmax(iir_gd)

    sections = len(sos)
    budget = run.cclk_hz / fs
    fir = run.cycles["fir"]
    iir = run.cycles["iir"]
    whole = run.cycles["audio_process"]

    s = "% Generated by coursework/E01-fir-iir/figures.py; do not edit.\n"
    s += _macro("SampleRate", "%d" % fs)
    s += _macro("CutoffHz", "%.0f" % design.CUTOFF_HZ)
    s += _macro("FirTaps", "%d" % design.FIR_TAPS)
    s += _macro("FirOrder", "%d" % (design.FIR_TAPS - 1))
    s += _macro("FirWindow", design.FIR_WINDOW)
    s += _macro("IirOrder", "%d" % design.IIR_ORDER)
    s += _macro("IirSections", "%d" % sections)
    s += _macro("IirShown", "%d" % IIR_SHOWN)
    s += _macro("IirReportLen", "%d" % len(run.impulse["iir"]))

    s += _macro("FirAtCutoff", _db(fir_design.at(design.CUTOFF_HZ)))
    s += _macro("IirAtCutoff", _db(iir_design.at(design.CUTOFF_HZ)))
    s += _macro("FirGroupDelay", "%.1f" % ((design.FIR_TAPS - 1) / 2))
    s += _macro("FirGroupDelayMs", "%.3f" % ((design.FIR_TAPS - 1) / 2 / fs * 1000))
    s += _macro("IirGroupDelayDc", "%.1f" % iir_gd[0])
    s += _macro("IirGroupDelayPeak", "%.1f" % iir_gd[peak])
    s += _macro("IirGroupDelayPeakHz", "%.0f" % fir_design.f[passband][peak])
    s += _macro("IirGroupDelayPeakMs", "%.3f" % (iir_gd[peak] / fs * 1000))

    s += _macro("FirIrErr", "\\num{%.1e}" % fir_ir_err)
    s += _macro("IirIrErr", "\\num{%.1e}" % iir_ir_err)
    s += _macro("IirIrPeak", "%.4f" % np.abs(iir_ref).max())

    s += _macro("CclkMHz", "%.0f" % (run.cclk_hz / 1e6))
    s += _macro("CyclesBudget", "%.0f" % budget)
    s += _macro("BlockFrames", "%d" % fir.frames)
    s += _macro("FirCycles", "%d" % fir.cycles)
    s += _macro("IirCycles", "%d" % iir.cycles)
    s += _macro("FirPerSample", "%.0f" % fir.per_sample)
    s += _macro("IirPerSample", "%.0f" % iir.per_sample)
    s += _macro("FirOverIir", "%.1f" % (fir.per_sample / iir.per_sample))
    s += _macro("AudioCycles", "%d" % whole.cycles)
    s += _macro("AudioPerFrame", "%.0f" % whole.per_sample)
    s += _macro("AudioLoad", "%.0f" % (100.0 * whole.per_sample / budget))
    # multiplies and adds per output sample, as written in fir.c and biquad.c
    s += _macro("FirMuls", "%d" % design.FIR_TAPS)
    s += _macro("FirAdds", "%d" % (design.FIR_TAPS - 1))
    s += _macro("IirMuls", "%d" % (5 * sections))
    s += _macro("IirAdds", "%d" % (4 * sections))
    s += _macro("FirOverIirOps", "%.1f" % (design.FIR_TAPS / (5.0 * sections)))
    s += _macro("FirStates", "%d" % design.FIR_TAPS)
    s += _macro("IirStates", "%d" % (2 * sections))
    s += _macro("IirCoeffs", "%d" % (5 * sections))

    rows = ["%.1f & %s & %s \\\\" % (f / 1000.0, _db(fir_design.at(f)), _db(iir_design.at(f))) for f in TABLE_HZ]
    s += _macro("GainRows", "\n".join(rows))
    return s


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--log", type=Path, default=BOARD_LOG, help="console log from make board")
    args = parser.parse_args()

    fs = design.SAMPLE_RATE
    h = design.fir(fs)
    sos = design.iir(fs)
    run = boardlog.read(args.log)
    for name in ("fir", "iir"):
        if name not in run.impulse:
            raise SystemExit("%s has no %s impulse response; run make board" % (args.log, name))

    fir_design = response.from_ba(h, fs=fs)
    iir_design = response.from_sos(sos, fs=fs)

    OUT.mkdir(parents=True, exist_ok=True)

    plot.impulse([
        plot.Series("FIR（%d 阶）" % (design.FIR_TAPS - 1), impulse=h,
                    measured=run.impulse["fir"]),
        plot.Series("IIR（%d 阶）" % design.IIR_ORDER, impulse=response.sos_impulse(sos, IIR_SHOWN),
                    measured=run.impulse["iir"][:IIR_SHOWN]),
    ], OUT / "impulse.pdf")

    curves = [
        plot.Series("FIR 设计", fir_design, style=FIR_STYLE),
        plot.Series("IIR 设计", iir_design, style=IIR_STYLE),
    ]
    plot.magnitude(curves, OUT / "magnitude.pdf", fmax_hz=fs / 2, ylim=(-120, 5),
                   marks_hz=[design.CUTOFF_HZ])
    plot.magnitude(curves, OUT / "magnitude_pass.pdf", fmax_hz=2 * design.CUTOFF_HZ, ylim=(-12, 1),
                   marks_hz=[design.CUTOFF_HZ])
    plot.phase(curves, OUT / "phase.pdf", fmax_hz=DETAIL_HZ)
    plot.group_delay(curves, OUT / "group_delay.pdf", fmax_hz=DETAIL_HZ, fs=fs)

    (OUT / "results.tex").write_text(results_tex(fs, h, sos, run, fir_design, iir_design))
    print("wrote %s" % OUT.relative_to(REPO))


if __name__ == "__main__":
    main()
