"""E02 figures and numbers for the report, from the dsp/ code run on the Mac.

    uv run coursework/E02-multirate/figures.py     # writes build/E02/

The responses come from dsplab.cdsp, which runs the same C the board runs on
the same 24-bit samples. results.tex holds the numbers the report quotes as
LaTeX macros, so the text never repeats a value by hand.
"""

from pathlib import Path

from dsplab import cdsp, plot, response

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "build" / "E02"

SAMPLE_RATE = 48000     # the codecs' rate (SAMPLE_RATE in adc_dac_playback.h)
# Impulse response length taken from the C chain
IR_LEN = 1024


def _macro(name, value):
    return "\\newcommand{\\%s}{%s}\n" % (name, value)


def main():
    fs = SAMPLE_RATE
    ir = cdsp.impulse(IR_LEN, channels=2)
    curves = [plot.Series("声道 %d" % ch, response.from_impulse(ir[:, ch], fs=fs), style={"color": "C%d" % ch})
              for ch in range(ir.shape[1])]

    OUT.mkdir(parents=True, exist_ok=True)
    plot.magnitude(curves, OUT / "magnitude.pdf", fmax_hz=fs / 2, ylim=(-120, 5))

    s = "% Generated by coursework/E02-multirate/figures.py; do not edit.\n"
    s += _macro("SampleRate", "%d" % fs)
    s += _macro("BlockFrames", "%d" % cdsp.BLOCK_FRAMES)
    s += _macro("IrLen", "%d" % IR_LEN)
    (OUT / "results.tex").write_text(s)
    print("wrote %s" % OUT.relative_to(REPO))


if __name__ == "__main__":
    main()
